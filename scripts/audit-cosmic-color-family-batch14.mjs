import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.argv[2] || '.');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const checks = [];
const expect = (name, ok) => checks.push([name, Boolean(ok)]);
const builder = read('resources/js/Pages/Websites/Builder.jsx');
const preview = read('resources/js/Pages/Marketplace/TemplateSiteRenderer.jsx');
const helper = read('resources/js/theme/legoSurface.js');
const families = read('resources/js/theme/colorFamilies.js');
const compiler = read('app/Helpers/CmsHtmlCompiler.php');
const footer = read('resources/js/Pages/Websites/GenerateFooter.jsx');
expect('shared Lego surface helper exists', helper.includes('resolveLegoSectionSurface') && helper.includes('legoSurfaceVars'));
expect('Builder uses shared resolver', builder.includes('resolveLegoSurfaceVars') && builder.includes('resolveLegoSectionSurface'));
expect('Builder exports semantic dark token', builder.includes("'--cosmic-color-dark': semanticPalette.dark"));
expect('Template preview uses shared resolver', preview.includes('resolveLegoSurfaceVars') && preview.includes('resolvedLegoSurface'));
expect('Template preview exports surface-alt', preview.includes("'--cosmic-bg-surface-alt': semanticPalette.surface_alt"));
expect('Custom brand publishes complete bg contract', families.includes("--cosmic-bg-primary-surface") && families.includes("--cosmic-color-dark"));
expect('Compiler exports semantic dark', compiler.includes('--cosmic-color-dark:{$semanticDark}'));
expect('Compiler exports surface alt background', compiler.includes('--cosmic-bg-surface-alt:{$semanticSurfaceMuted}'));
expect('Compiler slate uses semantic dark', compiler.includes("$bg = 'var(--cosmic-color-dark,#0F172A)'"));
expect('Footer still uses semantic shell resolver', footer.includes('resolveShellSurface(effectiveMegaTheme, semanticPalette)'));
expect('Footer CTA has guarded semantic text', footer.includes("'--cosmic-footer-cta-text': footerCtaText"));
const failed = checks.filter(([,ok])=>!ok);
for (const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`);
console.log(`\n${checks.length-failed.length}/${checks.length} checks passed`);
if (failed.length) process.exit(1);
